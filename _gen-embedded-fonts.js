// Generates lib/embedded-fonts.js: base64 TTFs for jsPDF export.
// The subset TTFs in lib/fonts/ttf/ are produced with pyftsubset (fonttools):
//   pyftsubset inter-400.ttf --unicodes="U+0020-007E,U+00A0-00FF,U+0131,
//     U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,
//     U+2190-2193,U+2212,U+2022" --layout-features="kern,liga,ccmp,locl" --no-hinting
// Static instances come from Google Fonts (css2 API with a legacy UA).
// Usage:  node _gen-embedded-fonts.js
// Why a JS file instead of fetching the .ttf at runtime: fetch() is blocked on
// file://, and PocketOffice must run from a USB stick with no server.
const fs = require('fs');
const path = require('path');
const ROOT = __dirname;

// file -> [family, jsPDF style]
const MAP = [
  ['inter-400.ttf',  'Inter', 'normal'],
  ['inter-700.ttf',  'Inter', 'bold'],
  ['inter-i400.ttf', 'Inter', 'italic'],
  ['inter-i700.ttf', 'Inter', 'bolditalic'],
  ['lora-400.ttf',   'Lora',  'normal'],
  ['lora-700.ttf',   'Lora',  'bold'],
  ['lora-i400.ttf',  'Lora',  'italic'],
  ['lora-i700.ttf',  'Lora',  'bolditalic'],
  ['jbmono-400.ttf', 'JetBrains Mono', 'normal'],
  ['jbmono-700.ttf', 'JetBrains Mono', 'bold'],
];

const entries = [];
for (const [file, fam, style] of MAP) {
  const p = path.join(ROOT, 'lib', 'fonts', 'ttf', file);
  if (!fs.existsSync(p)) { console.error('Missing ' + p); process.exit(1); }
  entries.push(`'${fam}|${style}':\n'${fs.readFileSync(p).toString('base64')}'`);
}
const out = `/* Auto-generated by _gen-embedded-fonts.js — do not edit by hand.\n` +
  `   Subset TTFs (SIL OFL 1.1, see lib/fonts/OFL-LICENSES.md) embedded as\n` +
  `   base64 so jsPDF exports can use the bundled fonts offline, file:// safe. */\n` +
  `window.EMBEDDED_TTF = {\n${entries.join(',\n')}\n};\n`;
const outFile = path.join(ROOT, 'lib', 'embedded-fonts.js');
fs.writeFileSync(outFile, out);
console.log('Wrote ' + outFile + ' (' + (fs.statSync(outFile).size / 1024).toFixed(0) + ' KB)');
